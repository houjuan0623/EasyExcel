const { _electron: electron } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { join, resolve } = require('node:path');
const { tmpdir } = require('node:os');
const { spawnSync } = require('node:child_process');
const root = resolve(__dirname, '..');
const parent = process.env.EXCELROUTER_TEST_DIR || tmpdir();
fs.mkdirSync(parent, { recursive: true });
const scratch = fs.mkdtempSync(join(parent, 'analysis-ui-'));
const python = join(root, '../.venv/Scripts/python.exe');
const fixture = spawnSync(python, [join(__dirname, 'analysis_fixture.py'), scratch], { encoding: 'utf8', windowsHide: true, env: { ...process.env, PYTHONIOENCODING: 'utf-8' } });
assert.equal(fixture.status, 0, fixture.stderr);
const source = JSON.parse(fixture.stdout).path;
const packaged = process.argv.includes('--packaged');
const env = { ...process.env, EXCELROUTER_USER_DATA: join(scratch, 'user-data'), EXCELROUTER_PYTHON: python };
for (const key of Object.keys(env)) if (['electron_run_as_node', 'electron_renderer_url'].includes(key.toLowerCase())) delete env[key];
if (packaged) {
  for (const key of Object.keys(env)) if (['path', 'pythonpath', 'pythonhome'].includes(key.toLowerCase())) delete env[key];
  env.Path = join(process.env.SystemRoot || 'C:/Windows', 'System32');
  env.EXCELROUTER_PYTHON = join(scratch, 'no-python.exe');
}
const launch = packaged ? { executablePath: process.env.EXCELROUTER_PACKAGED_EXE, args: [], cwd: scratch } : { args: [root] };
let app, stage = 'launch';
async function main() {
  app = await electron.launch({ ...launch, env, timeout: 45000 });
  try {
    const page = await app.firstWindow();
    page.setDefaultTimeout(45000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    await page.getByText('本地引擎已就绪', { exact: true }).waitFor();
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1500, 1000));
    await page.getByRole('button', { name: '统计分析', exact: true }).click();
    await app.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, source);
    await page.getByRole('button', { name: '选择分析文件', exact: true }).click();
    await page.getByLabel('数据块 1 区域', { exact: true }).waitFor();
    await page.getByLabel('数据块 1 区域', { exact: true }).fill('A3:F123');
    stage = 'range_picker';
    await page.getByRole('button', { name: '选择数据块 1 区域', exact: true }).click();
    const picker = page.getByRole('dialog', { name: '选择分析数据区域', exact: true });
    await picker.getByLabel('选区渲染方式', { exact: true }).selectOption('basic');
    await picker.locator('[data-analysis-cell="A3"]').waitFor();
    const start = await picker.locator('[data-analysis-cell="A3"]').boundingBox();
    const end = await picker.locator('[data-analysis-cell="D8"]').boundingBox();
    await page.mouse.move(start.x + 20, start.y + 12); await page.mouse.down();
    await page.mouse.move(end.x + 20, end.y + 12, { steps: 6 }); await page.mouse.up();
    assert.equal(await picker.getByLabel('所选分析区域', { exact: true }).inputValue(), 'A3:D8');
    await picker.getByRole('button', { name: '选择整列 B', exact: true }).click();
    await picker.getByRole('button', { name: '选择整列 D', exact: true }).click({ modifiers: ['Shift'] });
    assert.equal(await picker.getByLabel('所选分析区域', { exact: true }).inputValue(), 'B:D');
    await picker.getByLabel('选区预览起始行', { exact: true }).fill('101');
    await picker.getByRole('button', { name: '跳转', exact: true }).click();
    await picker.locator('[data-analysis-cell="A121"]').waitFor();
    await picker.getByRole('button', { name: '选择整行 121', exact: true }).click();
    assert.equal(await picker.getByLabel('所选分析区域', { exact: true }).inputValue(), '121:121');
    await page.screenshot({ path: join(scratch, '01-range-picker.png') });
    await picker.getByLabel('所选分析区域', { exact: true }).fill('A3:F123');
    await picker.getByRole('button', { name: '使用此区域', exact: true }).click();
    stage = 'bar_chart';
    await page.getByRole('button', { name: '读取数据并检查字段', exact: true }).click();
    await page.getByLabel('数值字段 预算金额', { exact: true }).check();
    await page.getByLabel('统计图分类或 X 轴', { exact: true }).selectOption({ label: '部门 · B' });
    await page.getByLabel('统计图标题', { exact: true }).fill('部门预算对比');
    await page.getByLabel('统计图单位', { exact: true }).fill('元');
    await page.getByLabel('统计图注解', { exact: true }).fill('虚构数据。按部门合计，包含完整 120 条记录。');
    await page.getByRole('button', { name: '生成图表预览', exact: true }).click();
    const preview = page.getByRole('region', { name: '统计图生成预览', exact: true });
    await page.locator('.analysis-live-preview img').waitFor();
    assert.equal(await page.locator('.analysis-live-preview img').evaluate(img => img.complete && img.naturalWidth > 100), true);
    await page.getByRole('button', { name: '加入 dashboard', exact: true }).click();
    assert.equal(await page.locator('.analysis-dashboard-card').count(), 1);
    stage = 'join';
    await page.getByRole('button', { name: '选择散点图', exact: true }).click();
    await page.getByRole('button', { name: '添加区域 / Sheet', exact: true }).click();
    await page.getByLabel('数据块 2 工作表', { exact: true }).selectOption(JSON.stringify([source, '补充指标']));
    await page.getByLabel('数据块 2 区域', { exact: true }).fill('A1:B121');
    await page.getByLabel('跨表组合方式', { exact: true }).selectOption('join');
    await page.getByRole('button', { name: '读取数据并检查字段', exact: true }).click();
    await page.getByLabel('数据块 1 关联字段', { exact: true }).selectOption({ label: '编号 · A' });
    await page.getByLabel('数据块 2 关联字段', { exact: true }).selectOption({ label: '编号 · A' });
    await page.getByLabel('统计图分类或 X 轴', { exact: true }).selectOption({ label: '数据块 1 / 预算金额 · D' });
    await page.getByLabel('数值字段 数据块 2 / 利润', { exact: true }).check();
    await page.getByLabel('统计图标题', { exact: true }).fill('预算与利润 · 跨 Sheet 关联');
    await page.getByRole('button', { name: '生成图表预览', exact: true }).click();
    await page.locator('.analysis-live-preview img').waitFor();
    await page.getByRole('button', { name: '加入 dashboard', exact: true }).click();
    assert.equal(await page.locator('.analysis-dashboard-card').count(), 2);
    stage = 'metric';
    await page.getByRole('button', { name: '新建图表', exact: true }).click();
    await page.getByRole('button', { name: '选择指标卡', exact: true }).click();
    await page.getByLabel('数据块 1 区域', { exact: true }).fill('A3:F123');
    await page.getByRole('button', { name: '读取数据并检查字段', exact: true }).click();
    await page.getByLabel('数值字段 预算金额', { exact: true }).check();
    await page.getByRole('button', { name: '生成图表预览', exact: true }).click();
    await page.locator('.analysis-live-preview .analysis-metric strong').waitFor();
    assert.equal(await page.locator('.analysis-live-preview .analysis-metric strong').textContent(), '726,000');
    await page.getByRole('button', { name: '加入 dashboard', exact: true }).click();
    await page.locator('.analysis-board').scrollIntoViewIfNeeded();
    await page.screenshot({ path: join(scratch, '02-dashboard.png') });
    await page.getByRole('button', { name: '上移图表 3', exact: true }).click();
    await page.getByRole('button', { name: '上移图表 2', exact: true }).click();
    assert.ok(await page.locator('.analysis-dashboard-card').first().getAttribute('class').then(v => v.includes('metric-card')));
    stage = 'save_export';
    const saved = join(scratch, 'analysis-plan.json');
    await app.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }); }, saved);
    await page.getByRole('button', { name: '保存方案', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.analysis-notice')?.textContent.includes('分析方案已保存'));
    assert.equal(JSON.parse(fs.readFileSync(saved, 'utf8')).cards.length, 3);
    assert.equal(fs.readFileSync(saved, 'utf8').includes('data:image'), false);
    await app.evaluate(({ dialog }, folder) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [folder] }); }, scratch);
    await page.getByRole('button', { name: '导出离线报告', exact: true }).click();
    await page.getByRole('button', { name: '打开报告文件夹', exact: true }).waitFor();
    const report = fs.readdirSync(scratch).find(n => n.startsWith('Dashboard_'));
    const html = fs.readFileSync(join(scratch, report, 'dashboard.html'), 'utf8');
    assert.ok(html.includes('data:image/png;base64,'));
    assert.ok(html.includes('726000'));
    assert.ok(fs.existsSync(join(scratch, report, 'chart_03_data.csv')));
    stage = 'persistence';
    await page.getByRole('button', { name: 'Excel 拆分', exact: true }).click();
    await page.getByRole('button', { name: '统计分析', exact: true }).click();
    assert.equal(await page.locator('.analysis-dashboard-card').count(), 3);
    await page.reload();
    await page.getByText('本地引擎已就绪', { exact: true }).waitFor();
    await page.getByRole('button', { name: '统计分析', exact: true }).click();
    assert.equal(await page.locator('.analysis-dashboard-card').count(), 3);
    assert.equal(await page.locator('.analysis-card-pending').count(), 3);
    await app.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, saved);
    await page.getByRole('button', { name: '导入方案', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.analysis-notice')?.textContent.includes('已导入配置'));
    await page.getByRole('button', { name: '刷新全部图表', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.analysis-card-pending').length === 0);
    stage = 'repair_changed_fields';
    const changed = JSON.parse(fs.readFileSync(saved, 'utf8'));
    changed.cards[0].config.fieldLabels[changed.cards[0].config.y[0]] = '原预算字段';
    const changedPath = join(scratch, 'changed-fields-plan.json');
    fs.writeFileSync(changedPath, JSON.stringify(changed));
    await app.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, changedPath);
    await page.getByRole('button', { name: '导入方案', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('.analysis-card-pending').length === 3);
    await page.getByRole('button', { name: '刷新全部图表', exact: true }).click();
    await page.waitForFunction(() => !document.querySelector('.analysis-busy'));
    assert.equal(await page.locator('.analysis-dashboard-card .analysis-error').count(), 1);
    assert.equal(await page.getByRole('button', { name: '导出离线报告', exact: true }).isDisabled(), true);
    await page.getByRole('button', { name: '编辑图表 1', exact: true }).click();
    await page.getByRole('button', { name: '读取数据并检查字段', exact: true }).click();
    await page.getByLabel('数值字段 预算金额', { exact: true }).check();
    await page.getByRole('button', { name: '生成图表预览', exact: true }).click();
    await page.locator('.analysis-live-preview .analysis-metric strong').waitFor();
    await page.getByRole('button', { name: '更新看板图表', exact: true }).click();
    assert.equal(await page.locator('.analysis-dashboard-card .analysis-error').count(), 0);
    assert.equal(await page.getByRole('button', { name: '导出离线报告', exact: true }).isEnabled(), true);
    assert.equal(errors.length, 0, errors.join('\n'));
    console.log(JSON.stringify({ ok: true, packaged, charts: 3, completeRecords: 120, exactMetric: 726000, crossSheetJoin: true, rangePickerAfterRow100: true, savedAndReloaded: true, editedAfterRefreshError: true, scratch }));
  } catch (error) { fs.writeFileSync(join(scratch, 'error.txt'), String(error.stack)); console.error('Failed stage:', stage); throw error; }
  finally { await app.close(); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
